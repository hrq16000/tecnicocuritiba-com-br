#!/usr/bin/env node
/**
 * Gate de CI — licenças e créditos das fotos públicas.
 *
 * Falha o build quando:
 *  - alguma imagem não é foto real de banco público permitido (bloqueia IA);
 *  - falta alt descritivo, fonte, URL da foto original ou licença;
 *  - o crédito não é renderizado no lugar correto (figcaption/ImageObject).
 *
 * Uso: node scripts/check-image-credits.mjs
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");

const ALLOWED_HOSTS = ["images.unsplash.com", "images.pexels.com"];
const AI_MARKERS = [
  "generated by ai",
  "ai-generated",
  "midjourney",
  "dall-e",
  "dalle",
  "stable-diffusion",
  "stablediffusion",
  "leonardo.ai",
  "firefly.adobe",
];

const errors = [];
const warnings = [];

// ---------------------------------------------------------------- registry
const imagesSrc = read("src/lib/images.ts");
const entries = [...imagesSrc.matchAll(/^\s{2}(\w+):\s*"([^"]+)",/gm)].map(([, k, v]) => [k, v]);
const map = Object.fromEntries(entries);
const keys = entries.filter(([k]) => !k.endsWith("Alt")).map(([k]) => k);

if (keys.length === 0) errors.push("src/lib/images.ts: nenhuma imagem encontrada.");

for (const key of keys) {
  const src = map[key];
  const alt = map[`${key}Alt`];
  const host = (src.match(/^https:\/\/([^/]+)/) || [])[1];

  if (!host || !ALLOWED_HOSTS.includes(host)) {
    errors.push(`${key}: host "${host || src}" não é banco público permitido (${ALLOWED_HOSTS.join(", ")}).`);
  }
  if (!/photo-[0-9a-z-]+/i.test(src)) {
    errors.push(`${key}: URL sem ID da foto original — impossível auditar licença.`);
  }
  if (!alt || alt.trim().length < 20) {
    errors.push(`${key}Alt: alt ausente ou curto demais (mínimo 20 caracteres, descritivo).`);
  }
  if (alt && /^(imagem|foto|picture|image)\b/i.test(alt.trim())) {
    errors.push(`${key}Alt: alt genérico ("${alt}") — descreva o que aparece na foto.`);
  }
  const low = `${src} ${alt || ""}`.toLowerCase();
  const ai = AI_MARKERS.find((m) => low.includes(m));
  if (ai) errors.push(`${key}: marcador de imagem gerada por IA ("${ai}") — proibido.`);
}

// -------------------------------------------------------------- credit lib
const creditsSrc = read("src/lib/imageCredits.ts");
for (const field of ["sourceUrl", "license", "licenseUrl", "creditLabel", "ogImageFromKey", "imageVariants"]) {
  if (!creditsSrc.includes(field)) errors.push(`src/lib/imageCredits.ts: campo/へelper "${field}" ausente.`);
}

// ------------------------------------------------- credit rendering places
const gallery = read("src/components/ServiceGallery.tsx");
if (!/creditLabel/.test(gallery) || !/<figcaption/i.test(gallery)) {
  errors.push("ServiceGallery: crédito precisa ser renderizado em <figcaption> (creditLabel).");
}
if (!/licenseUrl/.test(gallery)) {
  errors.push("ServiceGallery: link para a licença (licenseUrl) ausente na legenda.");
}
if (!/title=\{/.test(gallery)) {
  warnings.push("ServiceGallery: nenhum atributo title dinâmico detectado nas imagens.");
}

const schema = read("src/components/ImageObjectSchema.tsx");
for (const field of ["creditText", "license", "acquireLicensePage", "contentUrl"]) {
  if (!schema.includes(field)) errors.push(`ImageObjectSchema: campo obrigatório "${field}" ausente no JSON-LD.`);
}

// --------------------------------------------------- local pages have both
const localPages = [
  "src/pages/bairros/BairroTemplate.tsx",
  "src/pages/AtendimentoCidade.tsx",
  "src/pages/AtendimentoCidadeBairro.tsx",
];
for (const p of localPages) {
  if (!fs.existsSync(path.join(ROOT, p))) continue;
  const s = read(p);
  const hasGallery = /LocalPhotoGallery|ServiceGallery/.test(s);
  if (!hasGallery) errors.push(`${p}: página local sem galeria de fotos reais.`);
  const hasSchema = /ImageObjectSchema|LocalPhotoGallery/.test(s);
  if (!hasSchema) errors.push(`${p}: página local sem ImageObject (crédito/licença) no JSON-LD.`);
}

// --------------------------------------------------------------- resultado
for (const w of warnings) console.warn(`⚠️  ${w}`);
if (errors.length) {
  console.error(`\n❌ check-image-credits: ${errors.length} problema(s) de crédito/licença\n`);
  errors.forEach((e) => console.error(` - ${e}`));
  process.exit(1);
}
console.log(`✅ check-image-credits: ${keys.length} fotos auditadas — fonte, alt, crédito e licença OK (0 imagens de IA).`);
