#!/usr/bin/env node
/**
 * check-ai-images.mjs — gate "Zero IA" (build + CI).
 *
 * Regra do projeto: é proibido usar imagens geradas por IA. Este gate varre
 * os rasters publicados (public/, src/assets/) procurando:
 *  1. Assinaturas textuais de geradores embutidas no binário/metadados
 *     (DALL·E, Midjourney, Stable Diffusion, Adobe Firefly, C2PA, ComfyUI…).
 *  2. Nomes de arquivo que indiquem origem em IA.
 *
 * Fotos reais (câmera/celular) e imagens de bancos com crédito (Unsplash)
 * não carregam essas assinaturas — após `photos:strip` os metadados são
 * removidos, então um flag aqui significa IA *não sanitizada* ou suspeita
 * real de origem. Revise e substitua por foto real.
 *
 * Uso: node scripts/check-ai-images.mjs   (exit 1 = bloqueia deploy)
 */
import fs from "node:fs";
import path from "node:path";

const IMAGE_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);
const ROOTS = ["public", "src/assets"];

/** Assinaturas de geradores de IA encontradas em metadados/chunks de imagem. */
const AI_SIGNATURES = [
  "DALL-E",
  "DALL·E",
  "Midjourney",
  "midjourney",
  "Stable Diffusion",
  "stable-diffusion",
  "stablediffusion",
  "Adobe Firefly",
  "Firefly Image",
  "c2pa",
  "C2PA",
  "ComfyUI",
  "comfyui",
  "AUTOMATIC1111",
  "NovelAI",
  "Leonardo.Ai",
  "Leonardo AI",
  "ideogram",
  "Ideogram",
  "Black Forest Labs",
  "FLUX.1",
  "GPT-4o",
  "Imagen 3",
  "AI-generated",
  "AI generated",
  "Generated by AI",
  "generated_image",
];

/** Nomes de arquivo que denunciam origem em IA. */
const FILENAME_RE =
  /(^|[._-])(ai-gen|ai_generated|aigen|midjourney|dall-?e|sdxl|stable-diffusion|firefly|comfyui)([._-]|$)/i;

/**
 * Exceções documentadas — identidade visual flat (logotipo/wordmark), NÃO
 * fotografia apresentada como real. A regra Zero IA existe para proteger a
 * prova fotográfica (E-E-A-T); estes arquivos são marca gráfica e seguem
 * aqui de forma explícita e auditável até o redesign vetorial do logo.
 * NÃO adicione fotos a esta lista.
 */
const BRAND_GRAPHICS_ALLOWLIST = new Set([
  "src/assets/logo.png",
  "public/lovable-uploads/b702f033-fd78-4d1e-ae32-2ad60f672710.png",
]);

function collect(target) {
  const files = [];
  for (const entry of fs.readdirSync(target, { withFileTypes: true })) {
    const full = path.join(target, entry.name);
    if (entry.isDirectory()) files.push(...collect(full));
    else if (IMAGE_EXT.has(path.extname(entry.name).toLowerCase())) files.push(full);
  }
  return files;
}

const files = ROOTS.filter((r) => fs.existsSync(r)).flatMap(collect);
const flagged = [];

for (const file of files) {
  const normalized = file.split(path.sep).join("/");
  if (BRAND_GRAPHICS_ALLOWLIST.has(normalized)) continue;
  const base = path.basename(file);
  const nameHit = base.match(FILENAME_RE);
  if (nameHit) {
    flagged.push({ file, reason: `nome suspeito ("${nameHit[0]}")` });
    continue;
  }
  let text;
  try {
    text = fs.readFileSync(file).toString("latin1");
  } catch {
    continue;
  }
  const hits = AI_SIGNATURES.filter((sig) => text.includes(sig));
  if (hits.length) {
    flagged.push({ file, reason: `assinatura de IA: ${hits.join(", ")}` });
  }
}

console.log(`check:ai-images — ${files.length} imagem(ns) analisadas`);

if (flagged.length === 0) {
  console.log("✓ Nenhuma imagem com assinatura de IA. Todas as fotos são reais.");
  process.exit(0);
}

for (const f of flagged) {
  console.error(`  ✗ ${f.file} → ${f.reason}`);
}
console.error(
  `\n✗ ${flagged.length} imagem(ns) com origem em IA detectada(s).\n` +
    "  Regra do projeto: somente fotos reais. Substitua o arquivo e rode novamente.",
);
process.exit(1);
